// Snapshots the popular meme templates from Imgflip into data/meme-images.js.
//
// The snapshot is deliberate: it keeps room creation free of a network call, keeps the
// caption engine pure and deterministic for tests, and lets the game run when Imgflip is
// slow or down. Re-run it to refresh the deck.
//
//   node scripts/fetch-meme-images.mjs
//
// Imgflip serves these images but does not own them, so it cannot license them onward.
// Their terms cover personal, non-commercial use; anything commercial needs rights
// obtained separately. Swapping this file's output for owned artwork is the exit route,
// and nothing outside data/meme-images.js needs to change when that happens.
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const SOURCE = "https://api.imgflip.com/get_memes";
const TARGET = resolve(process.cwd(), "data/meme-images.js");
const MIN_SIDE = 300;

function usable(meme) {
  return Boolean(meme.id && meme.name && meme.url) &&
    meme.width >= MIN_SIDE &&
    meme.height >= MIN_SIDE;
}

function toCard(meme) {
  return {
    id: `im-${meme.id}`,
    name: meme.name,
    url: meme.url,
    width: meme.width,
    height: meme.height
  };
}

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`Imgflip answered ${response.status}`);
}

const body = await response.json();
if (!body.success) {
  throw new Error(body.error_message || "Imgflip refused the request");
}

const cards = body.data.memes
  .filter(usable)
  .map(toCard)
  .sort((left, right) => left.id.localeCompare(right.id));

const file = `// Generated by scripts/fetch-meme-images.mjs. Do not edit by hand.
//
// Image templates hosted by Imgflip, which serves them but does not own them. See the
// script header before using these anywhere commercial.
export const MEME_IMAGES = ${JSON.stringify(cards, null, 2)};

export function memeImageById(id) {
  return MEME_IMAGES.find((image) => image.id === id);
}
`;

await writeFile(TARGET, file, "utf8");
console.log(`Wrote ${cards.length} image cards to data/meme-images.js`);
